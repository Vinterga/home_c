/******************************************************************************
F1) СОРТИРОВКА ПО ВОЗРАСТАНИЮ
Написать только одну функцию, которая сортирует массив 
по возрастанию. Необходимо реализовать только одну функцию, 
всю программу составлять не надо.
Строго согласно прототипу. Имя функции и все аргументы должны быть: 
void sort_array(int size, int a[]).
    Формат входных данных: Функция принимает на вход, 
первый аргумент - размер массива, второй аргумент - адрес нулевого элемента.
    Формат результата: Функция ничего не возвращает. 
Производит сортировку переданного ей массива по возрастанию.
*******************************************************************************/
void sort_array(int size, int a[]) {
    // Внешний цикл: проходим по массиву size-1 раз
    for (int i = 0; i < size - 1; i++) { 
        // Внутренний цикл: каждый раз проходим на один элемент меньше,
        // так как самый большой элемент уже всплыл в конец
        for (int j = 0; j < size - i -1; j++) { 
            // Сравниваем соседние элементы используя адресную арифметику
            // *(a + j) эквивалентно a[j] - получаем значение по адресу a + j
            // *(a + j + 1) эквивалентно a[j + 1] - следующий элемент
            if (*(a + j) > *(a + j + 1)) {
                // Если текущий элемент больше следующего, то меняем их местами
                int temp = *(a + j);        // Сохраняем значение текущего элемента
                *(a + j) = *(a + j + 1);    // Заменяем текущий элемент следующим
                *(a + j + 1) = temp;        // Заменяем следующий элемент сохраненным значением
            }
        }
    }
}