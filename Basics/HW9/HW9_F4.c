/******************************************************************************
F4) ЦИФРЫ В СТРОКЕ
Написать только одну функцию. Всю программу отправлять не надо. 
Вывести в порядке возрастания цифры, входящие в строку. 
Цифра - количество. Функция должно строго соответствовать прототипу:
void print_digit(char s[])
- Формат входных данных: Строка из английских букв, пробелов, знаков препинания и цифр
- Формат результата: Функция должна принмать на вход строку и выводить на печать по формату: 
Цифра пробел количество.
*******************************************************************************/
#include <stdio.h>

void print_digit(char s[]) {
    // Создаем массив для подсчета количества каждой цифры (0-9)
    int count[10] = {0}; // Инициализируем все элементы нулями
    
    // Проходим по каждому символу строки до тех пор, пока не встретим нулевой символ (конец строки)
    for (int i = 0; s[i] != '\0'; i++) {
        // Проверяем, является ли текущий символ цифрой от '0' до '9'
        if (s[i] >= '0' && s[i] <= '9') {
            // Преобразуем символ-цифру в соответствующее числовое значение
            int digit = s[i] - '0'; // Вычитаем код символа '0', чтобы получить число от 0 до 9
            count[digit]++;         // Увеличиваем счетчик для этой цифры
        }
    }
    
    // Теперь выводим результаты для всех цифр от 0 до 9
    for (int digit = 0; digit < 10; digit++) {
        // Проверяем, встречалась ли данная цифра в строке
        if (count[digit] > 0) {
            // Выводим цифру и количество ее вхождений в формате "цифра пробел количество"
            printf("%d %d\n", digit, count[digit]);
        }
    }
}