/******************************************************************************
C12) Sin КАК СУММА РЯДА
Составить функцию, которая вычисляет синус как сумму ряда 
(с точностью 0.001)
sin(x) = x - x3/3! + x5/5! - x7/7! + ...(x в радианах)
float sinus(float x)
Input format: Одно число от 0 до 90
Output format: Вещественное число в формате "%.3f"
*******************************************************************************/
#include <stdio.h>

//функция вычисления синуса через ряд Тейлора
float sinus(float x_degrees) {
    //1. Константа pi для перевода градусов в радианы
    const float PI = 3.1415926535f;
    
    //2. Переводим градусы в радианы (рад = гр * пи / 180)
    float x_rad = x_degrees * PI / 180.0f;
    
    //3. Инициализируем переменные
    float sum = 0; //сумма ряда (результат)
    float term = x_rad; //текущий член ряда
    float sign = 1; //знак члена (+1 или -1)
    int n = 1; //счетчик для нечетных чисел (1, 3, 5 итд)
   
    // Цикл работает пока модуль текущего члена >= 0.001
    while (term >= 0.001f || -term >= 0.001f) {
        // 1. Добавляем текущий член к сумме
        sum += sign * term;
        
        // 2. Меняем знак для следующего члена
        sign = -sign;
        
        // 3. Умножаем текущий член на x^2 (готовим числитель следующего члена)
        term = term * x_rad * x_rad;
        
        // 4. Увеличиваем степень на 2 (переходим к следующей нечётной степени)
        n += 2;
        
        // 5. Делим на (n-1)*n - новые множители для факториала
        term = term / ((n - 1) * n);
    }
    
    return sum;
}

int main() {
    float angle;
    scanf("%f", &angle);
    printf("%.3f\n", sinus(angle));
    return 0;
}
