/******************************************************************************
C15) ЦИФРЫ ПО ВОЗРАСТАНИЮ
Составить функцию логическую функцию, которая определяет, верно ли, что в заданном числе 
все цифры стоят по возрастанию. Используя данную функцию решить задачу. int grow_up(int n)
Input format: Одно целое неотрицательное число
Output format: Ответ YES или NO
*******************************************************************************/
#include <stdio.h>


int grow_up(int n) {
    
    //1. Если число состоит из одной цифры - сразу возвращаем 1 (true),
    //потому что одна цифра автоматически "по возрастанию"
    if (n < 10) {
        return 1;
    }
    
    int last_digit = n % 10; //последняя цифра числа (самая правая)
    n = n / 10;              //убираем последнюю цифру из числа
    
    //2. Основной цикл: обрабатываем оставшиеся цифры
    while (n > 0) {
        int current_digit = n % 10; //Берем следующую цифру (справа налево)
        
        //3. Проверяем условие возрастания:
        //Цифры должны идти по возрастанию слева направо, а это значит, что
        //при движении справа налева каждая следующая цифра должна быть БОЛЬШЕ предыдущей
        if (current_digit >= last_digit) {
            //4. Если текущая цифра больше или равна последней - нарушение порядка
            return 0;   //не по возрастанию
        }
        
        //5. Обновляем значения для следующего шага
        last_digit = current_digit; // Теперь текущая цифра становится последней
        n = n / 10;                 //Убираем обработанную цифру
    }
    
    //6. Если дошли сюда - все цифры в порядке возрастания
    return 1;
}

int main()
{
    int n;  // Переменная для ввода числа
    
    // 1. Ввод числа
    scanf("%d", &n);
    
    // 2. Проверяем с помощью функции
    if (grow_up(n)) {
        printf("YES\n");
    } else {
        printf("NO\n");
    }
    
    return 0;
}