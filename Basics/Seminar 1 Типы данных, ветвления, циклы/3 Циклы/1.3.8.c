#include <stdio.h>
#include <stdbool.h>  // Для использования типа bool

// Функция проверки, является ли число простым
bool is_prime(int num) {
    // 1. Простые числа начинаются с 2
    if (num < 2) {
        return false;
    }
    
    // 2. Проверяем делители от 2 до квадратного корня из числа
    //    (если число делится на что-то в этом диапазоне - оно не простое)
    for (int i = 2; i * i <= num; i++) {
        if (num % i == 0) {
            return false;  // Нашли делитель - число не простое
        }
    }
    
    return true;  // Делителей не найдено - число простое
}

int main() {
    int n;  // Сколько простых чисел нужно найти
    
    // 1. Ввод количества простых чисел
    printf("Введите количество простых чисел (n): ");
    scanf("%d", &n);
    
    // 2. Проверка корректности ввода
    if (n <= 0) {
        printf("Ошибка: n должно быть положительным числом!\n");
        return 1;
    }
    
    // 3. Поиск и вывод первых n простых чисел
    int count = 0;  // Счетчик найденных простых чисел
    int num = 2;    // Первое простое число
    
    printf("Первые %d простых чисел:\n", n);
    
    // Пока не нашли n простых чисел
    while (count < n) {
        // Проверяем, является ли текущее число простым
        if (is_prime(num)) {
            printf("%d ", num);  // Выводим простое число
            count++;             // Увеличиваем счетчик
        }
        num++;  // Переходим к следующему числу
    }
    
    printf("\n");  // Переход на новую строку после вывода
    
    return 0;
}