/******************************************************************************
Сколько раз выполнится цикл
*******************************************************************************/
#include <stdio.h>

int main()
{
    int i, a = 1;
    
    for (i = 1; i >= 3; i--) a++; //0 раз, а = 1
    
    int k, b = 1;
    
    for (k = 1; k <= 4; k--) b++; //зациклилось
    
    printf("%d\n%d\n", a, b);
    
    return 0;
}

