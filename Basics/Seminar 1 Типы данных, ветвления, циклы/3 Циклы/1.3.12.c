// Это комментарий. Препроцессор его проигнорирует.
// #include - это директива препроцессора. Она подключает библиотеки.
// stdio.h - Standard Input Output header. Содержит объявления функций для ввода/вывода.
#include <stdio.h>

// main - главная функция. int - тип возвращаемого значения (целое число).
// void в скобках - аргументы функции (пока их нет).
int main(void) {
    // printf - функция для вывода на консоль.
    // \n - управляющий символ переноса строки.
    printf("Hello, World!\n");
    
    // return 0; - возвращает операционной системе код успешного завершения.
    return 0;
}