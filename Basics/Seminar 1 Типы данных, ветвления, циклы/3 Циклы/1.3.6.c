/******************************************************************************
8) Дано натуральное число n.
Получить все его натуральные делители
*******************************************************************************/
#include <stdio.h>

int main()
{
    int n;
    
    scanf("%d", &n);
    
     //Проверка, что число натуральное (больше 0)
    if (n <= 0) {
        printf("Число должно быть натуральным (больше 0)!\n");
        return 1;  // Завершаем программу с кодом ошибки
    }
    
   // Вывод заголовка
    printf("Делители числа %d: ", n);
    
    // Основной цикл перебора всех возможных делителей
    // Перебираем все числа от 1 до n включительно
    for (int i = 1; i <= n; i++) {
        // Проверяем, делится ли n на i без остатка
        if (n % i == 0) {
            // Если делится, выводим этот делитель
            printf("%d ", i);
        }
    }
    
    // 7. Переход на новую строку после вывода всех делителей
    printf("\n");
    
    return 0;
}