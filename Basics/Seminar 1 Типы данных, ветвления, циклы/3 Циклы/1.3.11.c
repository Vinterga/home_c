#include <stdio.h>

int main() {
    int i, count = 0;  // Инициализация счетчика
    
    // Цикл по всем числам от 102 до 987 включительно
    for (i = 102; i <= 987; i++) {
        // Выделяем три цифры числа:
        int d1 = i % 10;        // Единицы (последняя цифра)
        int d2 = i % 100 / 10;  // Десятки (средняя цифра)
        int d3 = i / 100;       // Сотни (первая цифра)

        // Проверяем, что все цифры различны
        if (d1 != d2 && d1 != d3 && d2 != d3) {
            count++;  // Увеличиваем счетчик, если все цифры разные
        }
    }
    
    printf("%d", count);  // Вывод результата
    return 0;
}