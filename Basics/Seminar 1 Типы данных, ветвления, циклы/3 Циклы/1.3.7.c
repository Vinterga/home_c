/******************************************************************************
8) Дано натуральное число n. 
Получить наименьшее число вида 2^k, превосходящее n.
(Используйте побитовые операции).
*******************************************************************************/
#include <stdio.h>

int main()
{
    int n;
    
    scanf("%d", &n);
    
    // 1. Проверка, что число не отрицательное
    if (n < 0) {
        printf("Число должно быть натуральным (не отрицательным)!\n");
        return 1;  // Завершаем программу с кодом ошибки
    }
    
    //2. Инициализация переменной для степени двойки
    unsigned int power = 1;  // Начинаем с 2^0 = 1
    //Используем unsigned int, чтобы избежать проблем с переполнением
    
    // 4. Основной алгоритм поиска степени двойки
    // Используем побитовый сдвиг влево для умножения на 2
    while (power <= n) {
        power = power << 1;  // Эквивалентно умножению на 2
    }
    /*Цикл выполняется, пока текущая степень двойки не превысит введенное число
    Операция << 1 - побитовый сдвиг влево на 1 позицию
    Побитовый сдвиг влево эквивалентен умножению на 2*/
    
    // 5. Вывод результата
    printf("Наименьшая степень двойки, превосходящая %d: %u\n", n, power);
    
    return 0;
}