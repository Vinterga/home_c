/******************************************************************************
G18) УДАЛИТЬ ПРОБЕЛЫ
В файле input.txt необходимо удалить все лишние пробелы (в начале предложения и сдвоенные пробелы). 
Для решения задачи разработать функцию. Результат записать в output.txt.
- Input Format: Строка из английских букв, 
                знаков препинания и пробелов. Не более 1000 символов.
- Output Format: Строка из английских букв, знаков препинания и пробелов.
*******************************************************************************/


#include <stdio.h>
#include <string.h>
#include <ctype.h>

//Ф-ция для удаления лишних пробелов 
void remove_extra_spaces(char *input, char *output) {
    int i = 0; //индекс для входной строки 
    int j = 0; //индекс для выходной строки 
    int space_flag = 0; //Флаг: 1 - если предыдущ. символ был пробелом 
    
    //Пропускаем все пробелы в начале строки
    while (isspace(input[i])) {
        i++;
    }
    
    //обрабатываем остав-ся часть строки 
    while (input[i] != '\0') {
        //Если текущий символ - пробел 
        if (isspace(input[i])) {
            //Если предыдущий символ не был пробелом, добавляем один пробел 
            if (!space_flag) {
                output[j] = ' ';
                j++;
                space_flag = 1; //Уст-м флаг пробела 
            }
            //Если пред-щий символ уже был пробелом, пропускаем текущий
        }
        else {
            //Если символ не пробел, копируем его в выход. строку 
            output[j] = input[i];
            j++;
            space_flag = 0; //Сбрасываем флаг пробела 
        }
        i++; //Переходим к след-му символу во входной строке 
    }
    
    //Удаляем пробел в конце строки, если он есть
    if (j > 0 && isspace(output[j-1])) {
        j--;
    }
    
    //ЗАвершаем выход. строку нулевым символом 
    output[j] = '\0';
}

int main() {
   //Объявляем массивы для хранения строк 
    char input_string[1001];  // Входная строка (1000 символов + \0)
    char output_string[1001]; // Выходная строка (будет короче или такой же длины)
    
    // Открываем файл input.txt для чтения
    FILE *input_file = fopen("input.txt", "r");
    
    //Проверяем, успешно ли открылся файл 
    if (input_file == NULL) {
        printf("Ошибка: не удалось открыть файл input.txt\n");
        return 1;  // Завершаем программу с кодом ошибки
    }
    
    //Считываем строку из файла
    if (fgets(input_string, 1001, input_file) == NULL) {
        printf("Ошибка: не удалось прочитать данные из файла\n");
        fclose(input_file);
        return 1;
    }
    
    //Закрываем входной файл 
    fclose(input_file);
    
    //Удаляем символ новой строки, если он есть в конце строки 
    int len = strlen(input_string);
    if (len > 0 && input_string[len-1] == '\n') {
        input_string[len-1] = '\0';
    }
    
    // Вызываем функцию для удаления лишних пробелов
    remove_extra_spaces(input_string, output_string);
    
    // Открываем файл output.txt для записи
    FILE *output_file = fopen("output.txt", "w");
    
    // Проверяем, успешно ли открылся файл
    if (output_file == NULL) {
        printf("Ошибка: не удалось открыть файл output.txt\n");
        return 1;
    }
    
    // Записываем обработанную строку в файл
    fprintf(output_file, "%s", output_string);
    
    // Закрываем выходной файл
    fclose(output_file);
    
    return 0;  // Успешное завершение программы
}