/******************************************************************************
G3) ПОСЛЕДНИЙ СИМВОЛ - НОМЕРА
В файле input.txt дана строка из не более 1000 символов. Показать номера символов, 
совпадающих с последним символом строки.
Результат записать в файл output.txt
- Input Format: Строка из не более 1000 символов
- Output Format: Целые числа через пробел - номера символа, 
который совпадает с последним символом строки.
*******************************************************************************/
#include <stdio.h>
#include <string.h>

int main()
{  
    char str[1001]; //м-в для хр-ия строки (1000 + 1 для \0)
    
    //Откр-м файл input.txt для чтения
    FILE *input_file = fopen("input.txt", "r");
    
    //Пров-м, успешно ли открылся файл
    if (input_file == NULL) {
        printf("Ошибка открытия файла input.txt\n");
        return 1; //Возвращаем код ошибки 
    }
    
    //Счит-м строку из файла с пом. fgets 
    //fgets как раз считывает до 1000 символов (1000-1) или до символа "\n" (новой строки)
    fgets(str, 1001, input_file);
    
    //Закр-м файл после чтения 
    fclose(input_file);
    
    //Находим длину строки с пом. strlen 
    int length = strlen(str); 
    
    //Удаляем символ новой строки (\n) из конца строки, если он есть 
    //Это нужно, потому что fgets вкл-т символ новой строки в строку
    if (length > 0 && str[length-1] == '\n') {
        str[length-1] = '\0'; //Заменяем символ новой строки на нулевой символ
        length--; //Уменьшаем длину на 1
    }
    
    //Проверяем, что строка не пустая
    if (length == 0) {
        printf("Строка пустая\n");
        return 1;
    }
    
    //Получаем последний символ строки
    char last_char = str[length-1];
    
    // Открываем файл output.txt для записи
    FILE *output_file = fopen("output.txt", "w");
    
    // Проверяем, успешно ли открылся файл
    if (output_file == NULL) {
        printf("Ошибка открытия файла output.txt\n");
        return 1;
    }
    
    //Перем. для отслеживания, был ли уже выведен хотя бы один номер
    int first = 1;
    
    //Проходим по всем символам строки (кроме последнего)
    for (int i = 0; i < length - 1; i++) {
        //Сравниваем текущий символ с последним символом строки
        if (str[i] == last_char) {
            // Если это не первый найденный символ, добавляем пробел перед числом 
            if (!first) {
                fprintf(output_file, " ");
            }
            
            //Выводим номер символа (нумерация с 1 => i + 1)
            fprintf(output_file, "%d", i);
            
            // Устанавливаем флаг, что уже был выведен хотя бы один номер
            first = 0;
        }
    }
    
    // Проверяем, нужно ли добавить последний символ
    // Последний символ всегда совпадает сам с собой, но по условию мы его не учитываем,
    // тк. в цикле мы проходим только до length-1
    
    // Закрываем файл после записи
    fclose(output_file);
    
    return 0; // Успешное завершение программы
}