/******************************************************************************
G2) СТРОКА И ЦИФРЫ 
Считать число N из файла input.txt. Сформировать строку из N символов. N четное число, 
не превосходящее 26. На четных позициях должны находится четные цифры в порядке возрастания, 
кроме 0, на нечетных позициях - заглавные буквы в порядке следования в английском алфавите. 
Результат записать в файл output.txt
- Input Format: Четное N ≤ 26
- Output Format: Строка из английских букв и цифр
*******************************************************************************/
#include <stdio.h>
#include <stdlib.h>

int main()
{
    int N; //для хранения N
    
    //Откр-м файл input.txt для чтения
    FILE *input_file = fopen("input.txt", "r");
    
    //Проверяем, успешно ли открылся файл 
    if (input_file == NULL) {
        printf("Ошибка открытия файла input.txt\n");
        return 1; //Возвращаем код ошибки
    }
    
    //Считываем число N из файла
    fscanf(input_file, "%d", &N);
    
    //Закрываем файл после чтения
    fclose(input_file);
    
    // Проверяем, что N четное и не превышает 26
    if (N % 2 != 0 || N > 26) {
        printf("Ошибка! N должно быть четным и не быть больше 26!\n");
        return 1;
    }
    
    //Создаем массив для хранения результирующей строки
    //Размер строки: N (+ 1 для завершающего символа \0) 
    char result[N + 1];
    
    //Инициализ-м перем-ые для генерации букв и цифр
    char current_letter = 'A'; //Начинаем с буквы "А"
    char current_digit = '2'; //Начинаем с цифры '2' (чет. цифры: 2, 4, 5, 8)
    
    //Заполняем строку по условию задачи 
    for (int i = 0; i < N; i++) {
        //Опред-м позицию в строке (начиная с 1)
        int position = i + 1;
        
        //Если позиция нечетная (1, 3, 5, ...)
        if (position % 2 == 1) {
            //Ставим заглавную букву в порядке алфавита 
            result[i] = current_letter;
            //Увеличиваем букву для след. нечет. позиции
            current_letter++;
        }
        // Если позиция четная (2, 4, 6, ...)
        else {
            //Ставим чет. цифру в пор. возрастания
            result[i] = current_digit;
            //Увел-м цифру на 2 для след-щей четной позиции 
            current_digit += 2;
            
            // Если цифра превысила '8', возвращаемся к '2'
            if (current_digit > '8') {
                current_digit = '2';
            }
        }
    }
    
    //Завершаем строку нулевым символом
    result[N] = '\0';
    
    //Откр-м файл 'output.txt' для записи
    FILE *output_file = fopen("output.txt", "w");
    
    //Проверяем, успешно ли открылся файл
    if (output_file == NULL) {
        printf("Ошибка открытия файла output.txt\n");
        return 1;
    }
    
    //ЗАписываем рез-т в файл 
    fprintf(output_file, "%s", result);
    
    //Закрываем файл после записи 
    fclose(output_file);
    
    return 0;
}