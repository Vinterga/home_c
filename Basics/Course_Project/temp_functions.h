//ОПРЕДЕЛЕНИЕ СТРУКТУРЫ ДЛЯ ХРАНЕНИЯ ДАННЫХ О ТЕМПЕРАТУРЕ 
/*Структура - это составной тип данных, объединяющий несколько переменных*/
typedef struct {
    int year;         //Год в формате YYYY
    int month;        //Месяц от 1 до 12
    int day;          //День месяца от 1 до 31
    int hour;         //Час от 0 до 23 
    int minute;       //Минуты от 0 до 59
    int temperature;  //Температура в градусах Цельсия от -99 до +99
} TemperatureRecord;
//Ключевое слово typedef используется для создания псевдонима типа данных, что упрощает использование структуры в коде 
//Теперь можно использовать TeperatureRecord для объявления переменных этого типа 

