//void перед названием функции означает, что функция не возвращает значение 

//Функция для чтения CSV файлов 
int read_csv(const char* filename, TemperatureRecord **data, int *total_records);
/*const char* filename - указатель на строку с именем файла, которую нельзя изменять
TemperatureRecord **data - указатель на указатель, чтобы изменять сам указатель на массив 
int *total_records - ук-ль на переменную, в которую запишется кол-во записей
Ф-ция возврт 0 при успехе, -1 - при ошибке*/

//Функция расчета и вывода статистики 
