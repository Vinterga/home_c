/******************************************************************************
C13) Cos как сумма ряда
Составить функцию, которая вычисляет синус как сумму ряда (с точностью 0.001)
cos(x) = 1 - x2/2! + x4/4! - x6/6! + ... (x в радианах)
float cosinus(float x)
Input format: Целое число от 0 до 90
Output format: Вещественное число в формате "%.3f"
*******************************************************************************/
#include <stdio.h>

//Функция вычисления косинуса через ряд Тейлора
float cosinus(float x_degrees) {
    //1. Константа PI для перевода градусов в радианы
    const float PI = 3.1415926535f;
    
    //2. Переводим градусы в радианы (рад = град * pi / 180)
    float x_rad = x_degrees * PI / 180.0f;
    
    //3. Инициализируем переменные:
    float sum = 0.0f;    //Сумма ряда
    float term = 1.0f;   //Текущий член ряда (начальный член при n=0)
    int n = 0;           //счетчик для четных степеней (0, 2, 4, ...)
    
    //4. Основной цикл вычислений
    //Будем суммировать члены ряда, пока их модуль >= 0.001
    while (term >= 0.001f || term <= -0.001f) {
        //5. Добавляем текущий член к сумме
        sum += term;
  
    
        //6. Вычисляем следующий член ряда:
        // след. член = текущий *(-х^2) / [(n+1)*(n+2)]
        term = term * (-x_rad * x_rad) / ((n + 1) * (n+2));
        
        //7. Увеличиваем степень для следующего члена
        // каждый шаг: 0 -> 2 -> 4 -> 6 и т.д.
        n += 2;
    }
    
    //8. Добавляем последний вычисленный член, если цикл завершился
    sum += term;
    
    //9. Для значений, близких к нулю (например, cos(90°))
    if (sum < 0.001f && sum > -0.001f) {
        sum = 0.0f;
    }

	return sum;
}


int main()
{
     float angle;  // Переменная для ввода угла
    
    // 1. Ввод угла в градусах
    scanf("%f", &angle);
    
    // 2. Вычисление косинуса
    float result = cosinus(angle);
    
    // 3. Вывод результата с точностью до трёх знаков
    printf("%.3f\n", result);

    return 0;
}