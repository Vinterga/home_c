/******************************************************************************
G4) СОВПАДЕНИЯ БУКВ
В файле input.txt даны два слова не более 100 символов каждое, 
разделенные одним пробелом. Найдите только те символы слов, которые 
встречаются в обоих словах только один раз. 
Напечатайте их через пробел в файл output.txt в лексикографическом порядке.
Input format: Два слова из маленьких английских букв через пробел. 
Длина каждого слова не больше 100 символов.
Output format: Маленькие английские буквы через пробел.
*******************************************************************************/
#include <stdio.h>
#include <string.h>

int main()
{
    char word1[101], word2[101]; //массивы для двух слов (100 симв + 1 для нулевого)
    
    FILE *input_file = fopen("input.txt", "r"); //откр-м файл input.txt для чтения
    
    //Пров-м, успешно ли открылся файл 
    if (input_file == NULL) {
        printf("Ошибка открытия файла input.txt\n");
        return 1;
    }
    
    //Считываем два слова из файла 
    fscanf(input_file, "%100s %100s", word1, word2);
  
 
    fclose(input_file);   // Закрываем файл после чтения
    
    //Создаем массивы для подсчета частоты встречаемости символов в каждом слове 
    //Индекс 0 соотв-т 'a', 1 - 'b', ..., 25 - 'z'(ASCII), от 0 до 25 = 26
    int count1[26] = {0}; //м-в для 1-ого слова, инициал-н нулями
    int count2[26] = {0}; // м-в для 2-ого слова, инициал-н нулями
    
    //Подсчитываем частоту каждого символа в 1-ом слове 
    int len1 = strlen(word1);
    for (int i = 0; i < len1; i++) {
        int index = word1[i] - 'a'; //преобр-м символ в индекс (от 0 до 25)
        count1[index]++; // Увел-м счетчик для данного символа
    }
    
     //Подсчитываем частоту каждого символа во 2-ом слове 
    int len2 = strlen(word2);
    for (int i = 0; i < len2; i++) {
        int index = word2[i] - 'a'; //преобр-м символ в индекс (от 0 до 25)
        count2[index]++; // Увел-м счетчик для данного символа
    }
    
     // Открываем файл output.txt для записи
    FILE *output_file = fopen("output.txt", "w");
    
    // Проверяем, успешно ли открылся файл
    if (output_file == NULL) {
        printf("Ошибка открытия файла output.txt\n");
        return 1;
    }
    
    //Введем флаг для отслеживания, был ли уже выведен 1-ый символ 
    //Это нужно для правильной расстановки пробелов 
    int first_printed = 1; //1 = "еще не выводили ни одного символа"
    
    //Проходим по всем буквам латиницы от "а" до "z"
    for (char c = 'a'; c <= 'z'; c++) {
        int index = c - 'a'; //Вычисляем индекс текущей буквы (о-25)
        
        /*Проверяем условия:
        1. Символ встреч-ся в первом слове ровно 1 раз
        2. Символ встреч-ся во втором слове ровно 1 раз*/
        if (count1[index] == 1 && count2[index] == 1) {
            //Если это не первый выводимый символ, добавляем пробел перед ним 
            if (!first_printed) {
                fprintf(output_file, " ");
            }
            
            //Выводим символ в файл
            fprintf(output_file, "%c", c);
            
            //Уст-м флаг, что мы уже вывели хотя бы один символ 
            first_printed = 0;
        }
    }
    
    //Закрываем файл после записи 
    fclose(output_file);
    
    return 0;
}