/******************************************************************************
С1) ПРЕФИКС И СУФФИКС 
На стандартном потоке ввода задаются две символьные строки, разделённые символом перевода строки. Каждая из строк не превышает по длине 10000 символов.
В строках не встречаются пробельные символы. На стандартный поток вывода напечатайте два числа, разделённых пробелом: 
первое число — длина наибольшего префикса первой строки, являющегося суффиксом второй; второе число — наоборот, длина наибольшего суффикса первой строки, 
являющегося префиксом второй. Сравнение символов проводите с учётом регистра (т.е. символы 'a' и 'A' различны).

# Входные данные: 
   don't_panic
   nick_is_a_mastodon
# Результат работы: 3 3
*******************************************************************************/
#include <stdio.h>
#include <string.h>

#define MAX_LEN 10000  // максимальная длина строки по условию

int main() {

    char s1[MAX_LEN + 1]; //Массивы для двух строк (+1 для заверш. нуля)
    char s2[MAX_LEN + 1];

    scanf("%s", s1);     //читаем строки
    scanf("%s", s2);

    int len1 = strlen(s1); //вычисляем длины строк
    int len2 = strlen(s2);

    // Первое число: длина наибольшего префикса s1, являющегося суффиксом s2
    int first = 0;  // искомое значение, пока 0

    // Перебираем возможные длины от максимально возможной (минимум из длин) вниз до 1 - Так мы найдём наибольшую длину первым же совпадением.
    int max_len = (len1 < len2) ? len1 : len2;  // максимальная длина, которую можно проверить
    for (int l = max_len; l > 0; l--) {
        // Сравниваем первые l символов s1 с последними l символами s2
        if (strncmp(s1, s2 + len2 - l, l) == 0) {  // s2 + len2 - l даёт указатель на начало последних l символов второй строки
            first = l;  // нашли совпадение
            break;      // выходим из цикла, так как это максимальная длина (идём сверху)
        }
    }

    // Второе число: длина наибольшего суффикса s1, являющегося префиксом s2
    int second = 0;

    // Снова перебираем длины от максимальной вниз
    for (int l = max_len; l > 0; l--) {
        // Сравниваем последние l символов s1 с первыми l символами s2
        if (strncmp(s1 + len1 - l, s2, l) == 0) {   // s1 + len1 - l даёт указатель на начало последних l символов первой строки
            second = l;  // нашли совпадение
            break;
        }
    } 
    
    printf("%d %d\n", first, second);

    return 0;
}