/******************************************************************************
B20) ПРОСТОЕ ЧИСЛО
Проверить число на простоту
Input format: Натуральное число
Output fromat: Если число является простым, напечатать YES, иначе - NO
*******************************************************************************/
#include <stdio.h>
#include <math.h>  // Для функции sqrt()

int main()
{
    int n;           //переменная для вводимого числа (кол-во чисел Фибоначчи для вывода)
    scanf("%d", &n); //считываем число с клавиатуры
   
   // Особые случаи: числа меньше 2 не являются простыми
    if (n < 2) {
        printf("NO\n");
        return 0;  // Завершаем программу
    }
    
    // Проверяем, является ли число 2 (единственное четное простое)
    if (n == 2) {
        printf("YES\n");
        return 0;
    }
    
    // Проверяем делимость на 2 (все четные числа, кроме 2, не простые)
    if (n % 2 == 0) {
        printf("NO\n");
        return 0;
    }
    
    int is_prime = 1;  // Флаг простоты числа (1 - простое, 0 - нет)
    int limit = sqrt(n) + 1;  // Вычисляем верхнюю границу проверки
    
    // Проверяем нечетные делители от 3 до limit
    for (int divisor = 3; divisor < limit; divisor += 2) {
        if (n % divisor == 0) {  // Если нашли делитель
            is_prime = 0;        // Число не простое
            break;               // Прерываем цикл
        }
    }
    
    // Выводим результат
    if (is_prime) {
        printf("YES\n");
    } else {
        printf("NO\n");
    }
    
    return 0;  // Завершаем программу
}