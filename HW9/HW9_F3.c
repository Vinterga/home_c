/******************************************************************************
F3) ЦИФРЫ ПО ВОЗРАСТАНИЮ
Написать функцию и программу демонстрирующую работу данной функции. 
Вывести в порядке возрастания цифры, входящие в десятичную запись 
натурального числа N, не более 1000 цифр. Цифра пробел сколько раз
данная цифра встречается в числе.
- Формат входных данных: Натуральное число не более 1000 цифр
- Формат результата: Цифры входящие в число через пробел в порядке 
    возрастания. От самой младшей цифры до самой старшей и количество.
*******************************************************************************/
#include <stdio.h>
#include <string.h>


void count_digits(char *number) { // Функция для подсчета и вывода цифр числа
    int count[10] = {0};          // Массив для подсчета цифр (0-9), инициализирован поперву нулями
    
    // Подсчет цифр в строке
    for (int i = 0; number[i] != '\0'; i++) {
        // Проверяем, что символ является цифрой
        if (number[i] >= '0' && number[i] <= '9') {
            // Преобразуем символ в числовое значение и увеличиваем счетчик
            int digit = number[i] - '0';
            count[digit]++;
        }
    }
    
    // Вывод результатов в порядке возрастания цифр (0-9)
    for (int digit = 0; digit < 10; digit++) {
        // Выводим только те цифры, которые встречаются в числе
        if (count[digit] > 0) {
            printf("%d %d\n", digit, count[digit]);
        }
    }
}

int main() {
    char number[1001]; // Массив для хранения числа как строки (1000 цифр + '\0')
    
    // Считываем число как строку
    scanf("%1000s", number);
    
    // Вызываем функцию для подсчета и вывода цифр
    count_digits(number);
    
    return 0;
}